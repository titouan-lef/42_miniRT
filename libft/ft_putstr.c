#include "libft.h"

int	ft_putstr(char *str)
{
	int	i;

	if (!str)
	{
		write(2, "(null)", 6);
		return (6);
	}
	i = 0;
	while (str[i])
		i++;
	write(2, str, i);
	return (i);
}
