int	ft_isalnum(int c)
{
	if (c <= 'Z' && c >= 'A')
		return (8);
	else if (c <= 'z' && c >= 'a')
		return (8);
	else if (c <= '9' && c >= '0')
		return (8);
	else
		return (0);
}
